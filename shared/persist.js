/**
 * Circuit Workspace — shared/persist.js
 * Планировщик записи состояния модуля. Фаза 1 трека «миграция на shared/db.js».
 *
 * ─── ЗАЧЕМ ОН ПОЯВИЛСЯ ──────────────────────────────────────────────────────
 *
 * `localStorage.setItem` возвращает управление сразу, `CWDB.put()` возвращает
 * промис. Между этими двумя фактами лежит вся сложность переезда на IndexedDB:
 * 79 вызовов `save()` в Конгрессах и Клиндарии написаны в предположении, что
 * после этой строки данные УЖЕ на диске (аудит — `docs/db-migration/01-audit.md`,
 * §2.1). Наивная замена на `async save()` превращает `save(); render();` в
 * гонку, а `beforeunload` промис ждать вообще не умеет.
 *
 * Приём тот же, что уже применён в `CWSender` и `CWTemplates`: работаем
 * синхронно с памятью, пишем отложенно. `save()` остаётся синхронной для
 * вызывающего — она обновляет память и ставит запись в очередь. Ни один из
 * 79 вызовов при этом не меняется.
 *
 * ─── ЧТО ЭТОТ ФАЙЛ ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ ──────────────────────────────────
 *
 * Он НЕ хранилище и ничего не сериализует. Он только решает, КОГДА позвать
 * `write()` модуля. Сериализация и сама запись остаются в коде модуля —
 * поэтому подмена хранилища в фазах 2–3 будет правкой одной функции модуля,
 * а не этого файла.
 *
 * Отсюда важное свойство, на которое можно опираться: **полезная нагрузка
 * собирается в момент ЗАПИСИ, а не в момент вызова `save()`.** Значит
 * отложенная запись физически не может записать устаревшее состояние — она
 * всегда пишет то, что лежит в памяти на момент записи. В частности, сброс
 * приложения (`localStorage.removeItem` + новое состояние) не рискует получить
 * поверх себя «догоняющую» запись старых данных.
 *
 * ─── ПОЧЕМУ ДВА ТАЙМЕРА, А НЕ ОДИН ──────────────────────────────────────────
 *
 * Обычный дебаунс откладывает запись, пока идут изменения. В Конгрессах
 * `save()` висит на `oninput` полей названия/места/даты — то есть при
 * непрерывном наборе запись не случилась бы НИКОГДА. Поэтому рядом с окном
 * ожидания (`delay`) стоит потолок (`maxDelay`): первое изменение в серии
 * заводит крайний срок, и позже него запись не уходит ни при каком наборе.
 *
 * ─── СТРАХОВКА НА ЗАКРЫТИИ ──────────────────────────────────────────────────
 *
 * Слой сам вешает `pagehide` / `beforeunload` / `visibilitychange`. Это не
 * удобство, а обязательная часть: без неё отложенная запись означает потерю
 * последней правки при закрытии вкладки, причём бесшумную. Забыть её в модуле —
 * ровно тот класс отказа, который в этом проекте уже случался дважды (пустой
 * `cw-sender` в копии, пустой архив Конгрессов), и оба раза выяснялось, когда
 * восстанавливать было уже нечем.
 *
 * ЗАМЕТКА ДЛЯ ФАЗ 2–3. Обработчик закрытия синхронен и промис ждать не может.
 * Когда `write()` начнёт писать в `CWDB`, на этом пути потребуется синхронное
 * зеркало в localStorage и сверка при загрузке — иначе последняя правка перед
 * закрытием уедет в никуда. Здесь это не решается: слой не знает, куда пишет
 * модуль. Пункт отмечен в `TODO.md`.
 *
 * `self` вместо `window` — файл единообразен с остальным общим слоем.
 */
(function (global) {
  'use strict';

  /* Окно ожидания и потолок. Значения подобраны так, чтобы запись оставалась
     незаметной для человека (набор в поле не дёргает диск на каждый символ),
     но задержка не превышала пары секунд — столько же живёт риск потерять
     правку при аварийном завершении вкладки. */
  var DEFAULT_DELAY = 400;
  var DEFAULT_MAX_DELAY = 2000;

  /**
   * Создать планировщик для одного хранилища.
   *
   * @param {Object}   opts
   * @param {string}   opts.name      — имя модуля, только для диагностики.
   * @param {Function} opts.write     — синхронная запись. Получает причину:
   *                                    'debounce' | 'flush' | 'unload' | своя.
   *                                    Модуль сам решает, отличать ли их: так,
   *                                    Клиндарий на 'unload' пишет через
   *                                    защищённый от чужой вкладки путь.
   * @param {number}   [opts.delay]
   * @param {number}   [opts.maxDelay]
   * @param {boolean}  [opts.autoFlushOnHide=true] — выключать только в тестах.
   */
  function create(opts) {
    var o = opts || {};
    var write = typeof o.write === 'function' ? o.write : null;
    if (!write) throw new Error('CWPersist.create: нужен write()');

    var delay = typeof o.delay === 'number' ? o.delay : DEFAULT_DELAY;
    var maxDelay = typeof o.maxDelay === 'number' ? o.maxDelay : DEFAULT_MAX_DELAY;

    var timer = null;      // окно ожидания
    var deadline = null;   // потолок: время, позже которого не откладываем
    var dirty = false;
    var writes = 0;        // счётчик реальных записей — для проверок

    function clearTimer() {
      if (timer !== null) { global.clearTimeout(timer); timer = null; }
    }

    /* Единственное место, где зовётся write(). Ошибку не глотаем и не
       показываем: сообщение о переполнении хранилища — дело модуля, у него
       для этого есть локализованный тост. Но флаг снимаем ДО вызова, иначе
       брошенное исключение оставило бы вечно грязное состояние и запись
       повторялась бы на каждом чихе. */
    function doWrite(reason) {
      clearTimer();
      deadline = null;
      dirty = false;
      writes++;
      write(reason);
    }

    function onTimer() {
      timer = null;
      if (!dirty) { deadline = null; return; }
      doWrite('debounce');
    }

    /**
     * Синхронный вызов из кода модуля вместо прежнего `save()`.
     * Ничего не пишет — помечает состояние изменённым и заводит таймеры.
     */
    function schedule() {
      dirty = true;
      var now = Date.now();
      if (deadline === null) deadline = now + maxDelay;
      clearTimer();
      /* Ждём меньшее из двух: обычное окно или остаток до крайнего срока. */
      var wait = Math.min(delay, Math.max(0, deadline - now));
      timer = global.setTimeout(onTimer, wait);
    }

    /**
     * Записать немедленно. Пишет ВСЕГДА, даже если изменений не было —
     * так же, как вело себя прежнее безусловное `save()` на закрытии вкладки
     * и в пятиминутном автосохранении Конгрессов. Это осознанно: страховочный
     * путь существует именно на случай кода, который поменял состояние и не
     * позвал `save()`.
     */
    function flush(reason) {
      doWrite(reason || 'flush');
    }

    /** Есть ли незаписанные изменения. Нужно там, где модуль читает
     *  сохранённое значение и обязан сначала догнать память. */
    function pending() { return dirty; }

    if (o.autoFlushOnHide !== false) {
      var onHide = function () { flush('unload'); };
      global.addEventListener('pagehide', onHide);
      global.addEventListener('beforeunload', onHide);
      if (global.document) {
        global.document.addEventListener('visibilitychange', function () {
          if (global.document.visibilityState === 'hidden') onHide();
        });
      }
    }

    return {
      schedule: schedule,
      flush: flush,
      pending: pending,
      /** Только для проверок: сколько раз реально дошло до записи. */
      writeCount: function () { return writes; },
      name: o.name || '',
    };
  }

  global.CWPersist = { create: create, DEFAULT_DELAY: DEFAULT_DELAY, DEFAULT_MAX_DELAY: DEFAULT_MAX_DELAY };
})(typeof self !== 'undefined' ? self : this);
