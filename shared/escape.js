/**
 * Circuit Workspace — shared/escape.js
 * Экранирование значения перед подстановкой в разметку. Одна функция на проект.
 *
 * ─── ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ ──────────────────────────────────────────────────
 *
 * До 28.08.2026 эта функция существовала в ШЕСТИ редакциях: `shared/docsview.js`,
 * `shared/print.js` (под именем `escapeText`), `pioneer-school/js/app.js`,
 * `documents/js/app.js`, `circuit-planner/app.js` (`App.utils.escapeHtml`),
 * `congress-project/js/utils.js`. И они РАСХОДИЛИСЬ: три экранировали
 * апостроф, три — нет.
 *
 * Именно расхождение и есть проблема, а не дубль сам по себе. Функция
 * безопасности в шести редакциях даёт ложное чувство защищённости: код,
 * написанный в расчёте на строгую версию, при переносе в соседний модуль
 * молча оказывается на слабой. Апостроф — не мелочь: значение, подставленное
 * в атрибут, ограниченный одинарными кавычками (`title='…'`), без него
 * разрывает атрибут и открывает вставку своего.
 *
 * ─── НАБОР СИМВОЛОВ — НАДМНОЖЕСТВО ВСЕХ ШЕСТИ ──────────────────────────────
 *
 * `& < > " '` — объединение того, что экранировала каждая из редакций. Ни один
 * вызывающий не получил меньше, чем имел; трое получили больше.
 *
 * `&` идёт ПЕРВЫМ и это не стиль: экранируй его после `<`, и `&lt;` превратится
 * в `&amp;lt;`, то есть на экране появится сам текст «&lt;».
 *
 * Обратная кавычка (`` ` ``) намеренно НЕ включена. Она нужна только для
 * незакавыченных атрибутов в старых версиях IE, которых у проекта нет, а
 * лишний символ в наборе — это лишнее расхождение с тем, что видит человек в
 * поле ввода.
 *
 * ─── ЭТО НЕ САНИТАЙЗЕР ─────────────────────────────────────────────────────
 *
 * Функция годится ровно для одного: подстановки ЗНАЧЕНИЯ в текстовый узел или
 * в значение атрибута. Она НЕ обеззараживает разметку целиком, НЕ годится для
 * содержимого `<script>`/`<style>` и НЕ делает безопасным `href="javascript:…"`.
 * Там, где значение подставляется в адрес, нужен `encodeURIComponent`, и он
 * уже используется — например, в `mailto:` у `pioneer-school/register.html`.
 *
 * ─── ЗАВИСИМОСТЬ ЖЁСТКАЯ, И ЭТО НАМЕРЕННО ──────────────────────────────────
 *
 * Потребители зовут `CWEscape.html()` без запасной ветки. Запасная ветка
 * означала бы седьмую редакцию функции — ровно то, что этот файл убирает.
 * Отсутствие файла обязано падать шумно, а не тихо экранировать иначе.
 * Наличие в прекэше каждого модуля стережёт `check-shared-precache.mjs`.
 */
(function (global) {
  'use strict';

  var MAP = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

  function html(value) {
    return String(value == null ? '' : value).replace(/[&<>"']/g, function (ch) {
      return MAP[ch];
    });
  }

  global.CWEscape = {
    /** Значение → безопасный текст для вставки в разметку. */
    html: html,

    /**
     * Значение → безопасный текст для значения атрибута.
     *
     * Это тот же набор символов, и отдельное имя заведено не ради разного
     * поведения, а ради читаемости места вызова: `CWEscape.attr(v)` в
     * `title="…"` сразу говорит, что подставляется атрибут. В Клиндарии такая
     * пара (`escapeHtml`/`escapeAttr`) уже была, и она тоже совпадала.
     */
    attr: html,
  };
})(typeof self !== 'undefined' ? self : this);
