/**
 * Circuit Workspace — shared/serviceyear.js
 * Служебный год: год, который начинается не в январе, а в сентябре.
 *
 * ЗАЧЕМ ОБЩИЙ СЛОЙ. До 24.08.2026 понятие жило ровно в одном месте —
 * `circuit-planner/app.js`: константа `App.config.serviceYearStartMonth` и три
 * функции рядом с ней. Школе пионеров то же понятие нужно для архива
 * прошедших школ, и копия завела бы ВТОРОЕ определение служебного года.
 * Этот класс дублирования (одна сущность описана в двух местах) уже трижды
 * давал в проекте тихие расхождения: правят одно место, про второе забывают,
 * а расходятся они не сразу и не громко. Поэтому — один файл на экосистему.
 *
 * ГРАНИЦА ОТВЕТСТВЕННОСТИ. Здесь лежит ТОЛЬКО календарная арифметика: к какому
 * служебному году относится дата, как он подписывается и где его границы.
 * Ничего про недели, визиты, школы и хранилища — это уже рабочее состояние
 * модуля, и оно остаётся у модуля. Правило то же, что у `CWDirectory`:
 * общий слой владеет ОПРЕДЕЛЕНИЕМ, модуль — своими данными.
 *
 * ПОЧЕМУ НАЧАЛО ГОДА — КОНСТАНТА, А НЕ НАСТРОЙКА. В Клиндарии это было
 * константой кода, в `settings` её не было никогда — проверено перед выносом.
 * Служебный год определён внешним календарём, а не предпочтением
 * пользователя, поэтому настройкой ему становиться незачем. Если однажды
 * понадобится (другая экосистема, другой отсчёт) — менять здесь, в одном
 * месте, и это ровно та причина, по которой файл существует.
 *
 * ПОДКЛЮЧЕНИЕ:
 *   <script src="../shared/serviceyear.js"></script>
 * плюс путь в прекэш service worker'а модуля — иначе офлайн-запуск потеряет
 * слой (проверяется `scripts/check-shared-precache.mjs`).
 *
 * ПОВЕДЕНИЕ ПЕРЕНЕСЕНО БАЙТ В БАЙТ. Функции ниже повторяют прежние реализации
 * Клиндария буквально, включая обращение с мусорным входом: `forDate()` на
 * неразбираемой дате вернёт `NaN`, а не `null` и не текущий год. Это выглядит
 * как недоделка, и чинить её при выносе НЕЛЬЗЯ: вынос обязан быть
 * поведенчески нулевым, иначе потом не отличить «сломалось от переноса» от
 * «сломалось от правки». Захочется строгости — отдельной задачей, с проверкой
 * всех 19 мест вызова.
 */
(function (global) {
  'use strict';

  /**
   * Месяц начала служебного года, нумерация JS (0 = январь).
   * 8 = сентябрь.
   */
  var START_MONTH = 8;

  /**
   * Разбор 'YYYY-MM-DD' в ЛОКАЛЬНУЮ полночь.
   *
   * Нужен именно локальный разбор: `new Date('2026-09-01')` даёт полночь UTC,
   * и к востоку от Гринвича дата остаётся первым сентября, а к западу
   * становится тридцать первым августа — то есть ПРЕДЫДУЩИМ служебным годом.
   * Копия `App.utils.parseLocalDate` Клиндария; общий слой не может звать
   * функцию модуля.
   */
  function parseLocalDate(value) {
    if (!value) return null;
    var parts = String(value).split('-').map(Number);
    if (parts.length !== 3 || parts.some(Number.isNaN)) return null;
    return new Date(parts[0], (parts[1] || 1) - 1, parts[2] || 1);
  }

  var CWServiceYear = {
    /** Месяц начала служебного года (0 = январь). Только чтение. */
    START_MONTH: START_MONTH,

    /**
     * Служебный год, к которому относится дата.
     * Принимает 'YYYY-MM-DD', Date или что угодно, что понимает `new Date()`.
     * @returns {number} год НАЧАЛА служебного года (для 2026/2027 это 2026)
     */
    forDate: function (date) {
      var d = (typeof date === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(date))
        ? parseLocalDate(date)
        : new Date(date);
      return d.getMonth() >= START_MONTH ? d.getFullYear() : d.getFullYear() - 1;
    },

    /**
     * Подпись служебного года: 2026 → '2026/2027'.
     * Разделитель именно косая черта; для имён файлов её меняют на месте
     * вызова (в Клиндарии — `.replace('/', '-')` в `pdfFilenameSuffix`),
     * потому что косая черта в имени файла недопустима.
     */
    label: function (year) {
      return year + '/' + (year + 1);
    },

    /**
     * Границы служебного года: первое сентября — тридцать первое августа.
     * Конец считается нулевым днём следующего месяца — это последний день
     * предыдущего, поэтому длина февраля и високосные годы учитываются сами.
     * @returns {{start: Date, end: Date}}
     */
    bounds: function (year) {
      return {
        start: new Date(year, START_MONTH, 1),
        end: new Date(year + 1, START_MONTH, 0),
      };
    },
  };

  global.CWServiceYear = CWServiceYear;
})(typeof self !== 'undefined' ? self : this);
